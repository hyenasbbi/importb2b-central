import assert from 'node:assert/strict';
import {handler} from '../netlify/functions/catalog.mjs';
import {createClient} from '@supabase/supabase-js';
const response=await handler({httpMethod:'GET',queryStringParameters:{slug:'importb2b'}});
assert.equal(response.statusCode,200,response.body);
assert.equal(response.headers['cache-control'],'no-store');
const payload=JSON.parse(response.body);
assert.ok(Array.isArray(payload.categories));
assert.ok(payload.products.length>0);
const visible=payload.categories.filter(c=>c.active).sort((a,b)=>a.sort_order-b.sort_order);
assert.equal(visible[0].name,'Camisetas');
assert.equal(visible.at(-1).name,'Vapers');
const names=new Set(visible.map(c=>c.name));
assert.ok(payload.products.every(p=>names.has(p.category)));
assert.ok(payload.products.some(p=>p.variants.some(v=>Object.hasOwn(v,'sale_price_ars'))));
assert.equal((await handler({httpMethod:'GET',queryStringParameters:{slug:'missing-test-catalog'}})).statusCode,404);
assert.equal((await handler({httpMethod:'POST'})).statusCode,405);
assert.equal((await handler({httpMethod:'OPTIONS'})).statusCode,204);
