import fs from 'node:fs';import vm from 'node:vm';import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../assets/js/catalog.js',import.meta.url),'utf8');
const methods=[{code:'cash',name:'Efectivo'},{code:'transfer',name:'Transferencia'},{code:'go_cuotas',name:'Go Cuotas',adjustment_kind:'percent',adjustment_direction:'surcharge',adjustment_value:12}];
const nodes=new Map();const $=s=>{if(!nodes.has(s))nodes.set(s,{innerHTML:'',textContent:''});return nodes.get(s)};
const context=vm.createContext({cart:[{price:10000,quantity:1}],data:{settings:{shipping_fee_ars:1000},payment_methods:methods},$,money:n=>String(n),esc:s=>String(s??'')});
vm.runInContext(source.slice(source.indexOf('  function totals('),source.indexOf('  function renderCart(')),context);
vm.runInContext(source.slice(source.indexOf('  function renderCheckoutPayments('),source.indexOf('  function updateCheckout(')),context);
assert.equal(context.totals('go_cuotas','pickup').total,11200);
assert.equal(context.totals('go_cuotas','shipping').total,12320);
assert.equal(context.totals('cash','shipping').total,11000);
assert.equal(context.totals('transfer','pickup').total,10000);
context.renderCheckoutPayments('go_cuotas','pickup');
assert.match($('#checkoutPaymentCards').innerHTML,/Recargo 12% incluido/);
assert.match($('#checkoutPaymentCards').innerHTML,/value="2" checked/);
assert.match($('#checkoutPaymentHint').textContent,/11200/);
methods[2].adjustment_value=15;context.renderCheckoutPayments('go_cuotas','shipping');
assert.equal(context.totals('go_cuotas','shipping').total,12650);
assert.match($('#checkoutPaymentCards').innerHTML,/Recargo 15% incluido/);
assert.ok(!$('#checkoutPaymentCards').innerHTML.includes('Ualá'));
console.log('PASS: Go Cuotas admin rate, shipping, cash/transfer totals, selected method and disclosed commission');
